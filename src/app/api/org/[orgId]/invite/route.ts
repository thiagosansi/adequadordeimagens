// Creates an invitation for a new member and optionally sends an email via Resend.
// If RESEND_API_KEY is not set, returns the invite link without sending email.
//
// Only org owners and admins can invite members.

import { NextResponse } from 'next/server'
import { createClient } from '@/lib/supabase/server'
import { createServiceClient } from '@/lib/supabase/service'

const ROLE_OPTIONS = ['admin', 'media_buyer', 'designer', 'viewer'] as const
type Role = (typeof ROLE_OPTIONS)[number]

interface InviteBody {
  email: string
  role: Role
}

export async function POST(
  request: Request,
  { params }: { params: Promise<{ orgId: string }> },
) {
  try {
    const { orgId } = await params
    const supabase = await createClient()
    const { data: { user } } = await supabase.auth.getUser()
    if (!user) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })

    const body = await request.json() as InviteBody
    const { email, role } = body

    if (!email || !ROLE_OPTIONS.includes(role)) {
      return NextResponse.json({ error: 'email and valid role are required' }, { status: 400 })
    }

    // Verify caller is owner or admin (RLS enforces this on insert, but check explicitly)
    const { data: membership } = await supabase
      .from('organization_members')
      .select('role')
      .eq('organization_id', orgId)
      .eq('user_id', user.id)
      .maybeSingle()

    if (!membership || !['owner', 'admin'].includes(membership.role)) {
      return NextResponse.json({ error: 'Forbidden' }, { status: 403 })
    }

    // Get org name for the email
    const db = createServiceClient()
    const { data: org } = await db
      .from('organizations')
      .select('name')
      .eq('id', orgId)
      .single()

    // Create invitation (token auto-generated by DB default)
    const { data: invitation, error: inviteError } = await db
      .from('organization_invitations')
      .insert({
        organization_id: orgId,
        email,
        role,
        invited_by: user.id,
      })
      .select('token')
      .single()

    if (inviteError || !invitation) {
      console.error('[invite] insert failed:', inviteError)
      return NextResponse.json({ error: 'Failed to create invitation' }, { status: 500 })
    }

    const origin = new URL(request.url).origin
    const inviteUrl = `${origin}/invite/${invitation.token}`

    // Send email if Resend API key is configured
    const resendKey = process.env.RESEND_API_KEY
    if (resendKey) {
      const { Resend } = await import('resend')
      const resend = new Resend(resendKey)
      const fromEmail = process.env.RESEND_FROM_EMAIL ?? 'no-reply@adframe.com.br'

      await resend.emails.send({
        from: fromEmail,
        to: email,
        subject: `Você foi convidado para ${org?.name ?? 'uma organização'} no AdFrame`,
        html: `
          <div style="font-family:sans-serif;max-width:520px;margin:0 auto;padding:32px 24px">
            <h2 style="margin:0 0 8px;font-size:20px;color:#0f172a">
              Convite para ${org?.name ?? 'organização'}
            </h2>
            <p style="color:#64748b;font-size:14px;margin:0 0 24px">
              Você foi convidado para participar como <strong>${role}</strong>.
              Clique no botão abaixo para aceitar.
            </p>
            <a href="${inviteUrl}"
               style="display:inline-block;background:#2563eb;color:#fff;font-size:14px;
                      font-weight:600;text-decoration:none;padding:12px 24px;border-radius:10px">
              Aceitar convite
            </a>
            <p style="color:#94a3b8;font-size:12px;margin:24px 0 0">
              Link válido por 7 dias. Se você não esperava este convite, ignore este e-mail.
            </p>
          </div>
        `,
      })
    }

    return NextResponse.json({ ok: true, inviteUrl, emailSent: !!resendKey })
  } catch (err) {
    console.error('[invite]', err)
    return NextResponse.json({ error: 'Internal server error' }, { status: 500 })
  }
}
